"""Hyprland runtime configuration generator (~/.config/hypr/kite-glass-runtime.conf)."""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from kite_settings.clamping import EffectiveGlassConfig
from kite_settings.models import HwProfile, KiteSettings, resolve_hypr_conf_path


def render_hypr_glass_conf(
    settings: KiteSettings,
    effective: EffectiveGlassConfig,
    hw: HwProfile,
) -> str:
    """Render deterministic Hyprland runtime overrides honoring HD 4400 blur bounds."""
    accent_hex = settings.accent_color.lstrip("#").upper()
    x1, y1, x2, y2 = effective.spring_curve_tuple
    blur_enabled_str = "true" if effective.blur_enabled else "false"
    blur_xray_str = "true" if effective.blur_xray else "false"
    anim_enabled_str = "true" if effective.animations_enabled else "false"

    lines = [
        "# Auto-generated by kite-settings — do not hand-edit.",
        f"# Hardware Tier: {hw.memory_tier} ({hw.ram_mb} MB) | Power: {hw.power_source}",
        f"# Effective Blur Tier: {effective.effective_tier} | Clamp: {effective.clamp_reason}",
        f"# Preset: {settings.theme_preset} | Battery Auto-Simplify: {str(settings.battery_glass_autosimplify).lower()}",
        "",
        "general {",
        f"    col.active_border = rgba({accent_hex}{effective.specular_alpha_hex}) rgba(FFFFFF44) 45deg",
        "    col.inactive_border = rgba(94A3B826)",
        "}",
        "",
        "decoration {",
        f"    rounding = {effective.rounding}",
        f"    active_opacity = {effective.active_opacity:.2f}",
        f"    inactive_opacity = {effective.inactive_opacity:.2f}",
        "",
        "    blur {",
        f"        enabled = {blur_enabled_str}",
        f"        size = {effective.blur_size}",
        f"        passes = {effective.blur_passes}",
        f"        xray = {blur_xray_str}",
        "        new_optimizations = true",
        "        ignore_opacity = true",
        "    }",
        "}",
        "",
        "animations {",
        f"    enabled = {anim_enabled_str}",
        f"    bezier = kiteSpring, {x1:.2f}, {y1:.2f}, {x2:.2f}, {y2:.2f}",
        f"    animation = windows, 1, {effective.anim_duration_windows_ds}, kiteSpring, popin 92%",
        f"    animation = windowsOut, 1, {max(1, effective.anim_duration_windows_ds - 1)}, kiteSpring, popin 92%",
        f"    animation = workspaces, 1, {effective.anim_duration_workspaces_ds}, kiteSpring, slide",
        "}",
        "",
    ]
    return "\n".join(lines)


def write_hypr_glass_conf(content: str, path: str | Path | None = None) -> Path:
    target = resolve_hypr_conf_path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    tmp_path: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=target.parent,
            prefix=".kite-glass-",
            suffix=".tmp",
            delete=False,
        ) as handle:
            tmp_path = handle.name
            handle.write(content)
        os.replace(tmp_path, target)
    except Exception:
        if tmp_path and os.path.exists(tmp_path):
            os.unlink(tmp_path)
        raise
    return target


def reload_hyprland(no_reload: bool = False) -> bool:
    if no_reload or sys.platform != "linux":
        return False
    if not os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
        return False
    if shutil.which("hyprctl") is None:
        return False
    result = subprocess.run(
        ["hyprctl", "reload"],
        check=False,
        timeout=3,
        capture_output=True,
        text=True,
    )
    return result.returncode == 0
