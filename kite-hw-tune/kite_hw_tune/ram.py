"""RAM tier detection, zram sizing, sysctl tuning, and subsystem profiles."""

from __future__ import annotations

import re

from kite_hw_tune.abstractions import CmdRunner, EnvWriter, ProcFs
from kite_hw_tune.models import (
    HardwareDetectionError,
    KiteAiSubsystem,
    MemoryProfile,
    OsxKvmSubsystem,
    PowerSource,
    RamTier,
    SubsystemsProfile,
    WaydroidSubsystem,
    WineSubsystem,
)

_MEMTOTAL_RE = re.compile(r"^MemTotal:\s+(\d+)\s*kB\s*$", re.IGNORECASE)

_TIER_MEMORY_SPECS: dict[RamTier, tuple[int, str, int, dict[str, int]]] = {
    "4G": (
        150,
        "lz4",
        260,
        {
            "vm.swappiness": 180,
            "vm.page-cluster": 0,
            "vm.watermark_boost_factor": 0,
        },
    ),
    "8G": (
        100,
        "zstd",
        350,
        {
            "vm.swappiness": 150,
            "vm.page-cluster": 0,
            "vm.vfs_cache_pressure": 75,
        },
    ),
    "16G": (
        50,
        "zstd",
        480,
        {
            "vm.swappiness": 100,
            "vm.page-cluster": 0,
            "vm.dirty_ratio": 10,
        },
    ),
}


def parse_meminfo_kb(proc_fs: ProcFs, path: str = "/proc/meminfo") -> int:
    """Parse MemTotal in kB from /proc/meminfo."""
    raw = proc_fs.read_text(path)
    if raw is None:
        raise HardwareDetectionError(f"Unable to read {path}")

    for line in raw.splitlines():
        match = _MEMTOTAL_RE.match(line.strip())
        if match:
            kb = int(match.group(1))
            if kb <= 0:
                raise HardwareDetectionError(f"Invalid MemTotal value in {path}: {kb} kB")
            return kb

    raise HardwareDetectionError(f"MemTotal not found or malformed in {path}")


def detect_ram_mb(proc_fs: ProcFs, path: str = "/proc/meminfo") -> int:
    """Detect total RAM in MiB from /proc/meminfo."""
    kb = parse_meminfo_kb(proc_fs, path=path)
    ram_mb = kb // 1024
    if ram_mb <= 0:
        raise HardwareDetectionError(f"Detected RAM too small: {ram_mb} MB")
    return ram_mb


def classify_ram_tier(ram_mb: int) -> RamTier:
    """Classify Folio 9480m RAM into 4G, 8G, or 16G tier."""
    if ram_mb <= 0:
        raise ValueError(f"ram_mb must be positive, got {ram_mb}")
    if ram_mb < 6144:
        return "4G"
    if ram_mb <= 12288:
        return "8G"
    return "16G"


def build_memory_profile(ram_mb: int) -> MemoryProfile:
    """Compute exact zram and sysctl settings for the given RAM size in MiB."""
    tier = classify_ram_tier(ram_mb)
    zram_percent, zram_algo, idle_budget_mb, sysctl = _TIER_MEMORY_SPECS[tier]
    zram_size_mb = (ram_mb * zram_percent) // 100
    return MemoryProfile(
        tier=tier,
        zram_percent=zram_percent,
        zram_size_mb=zram_size_mb,
        zram_algo=zram_algo,  # type: ignore[arg-type]
        idle_budget_mb=idle_budget_mb,
        sysctl=dict(sysctl),
    )


def build_subsystems_profile(tier: RamTier, power_source: PowerSource = "AC") -> SubsystemsProfile:
    """Build Wine (pinned DXVK 1.10.3), Waydroid, OSX-KVM, and Kite AI policies by RAM/power."""
    is_4g_battery = tier == "4G" and power_source == "Battery"
    kite_ai = KiteAiSubsystem(
        socket_only=True,
        background_watch=not is_4g_battery,
        default_tier0_only=is_4g_battery,
        max_input_tokens=400,
        io_scheduling_class="idle",
    )
    if tier == "4G":
        return SubsystemsProfile(
            wine=WineSubsystem(dxvk_version="1.10.3", ntsync=True, prewarm=False),
            waydroid=WaydroidSubsystem(
                idle_policy="freeze_then_teardown",
                teardown_after_sec=300,
                prewarm=False,
            ),
            osx_kvm=OsxKvmSubsystem(hugepages_on_demand=False),
            kite_ai=kite_ai,
        )
    if tier == "8G":
        return SubsystemsProfile(
            wine=WineSubsystem(dxvk_version="1.10.3", ntsync=True, prewarm=False),
            waydroid=WaydroidSubsystem(
                idle_policy="cgroup_freeze",
                teardown_after_sec=None,
                prewarm=False,
            ),
            osx_kvm=OsxKvmSubsystem(hugepages_on_demand=False),
            kite_ai=kite_ai,
        )
    return SubsystemsProfile(
        wine=WineSubsystem(dxvk_version="1.10.3", ntsync=True, prewarm=True),
        waydroid=WaydroidSubsystem(
            idle_policy="prewarmed",
            teardown_after_sec=None,
            prewarm=True,
        ),
        osx_kvm=OsxKvmSubsystem(hugepages_on_demand=True),
        kite_ai=kite_ai,
    )


def render_sysctl_conf(memory: MemoryProfile) -> str:
    """Render runtime sysctl snippet for /run/sysctl.d/99-kite-hw-tune.conf."""
    lines = [
        f"# Auto-generated by kite-hw-tune for RAM tier {memory.tier}",
    ]
    for key, value in memory.sysctl.items():
        lines.append(f"{key} = {value}")
    return "\n".join(lines) + "\n"


def apply_memory_tuning(
    memory: MemoryProfile,
    cmd: CmdRunner,
    env_writer: EnvWriter,
    *,
    sysctl_conf_path: str = "/run/sysctl.d/99-kite-hw-tune.conf",
    dry_run: bool = False,
) -> list[str]:
    """Write sysctl runtime config and apply sysctl/zram settings."""
    warnings: list[str] = []
    if dry_run:
        return warnings

    env_writer.write_text(sysctl_conf_path, render_sysctl_conf(memory))

    if cmd.which("sysctl"):
        for key, value in memory.sysctl.items():
            res = cmd.run(["sysctl", "-w", f"{key}={value}"])
            if res.returncode != 0:
                warnings.append(
                    f"sysctl -w {key}={value} exited {res.returncode}: {res.stderr.strip()}"
                )
    else:
        warnings.append("sysctl binary not found; skipped live sysctl application")

    if cmd.which("zramctl") and cmd.which("mkswap") and cmd.which("swapon"):
        if cmd.which("swapoff"):
            cmd.run(["swapoff", "/dev/zram0"])
        cmd.run(["zramctl", "--reset", "/dev/zram0"])

        zram_res = cmd.run(
            [
                "zramctl",
                "/dev/zram0",
                "--size",
                f"{memory.zram_size_mb}M",
                "--algorithm",
                memory.zram_algo,
            ]
        )
        if zram_res.returncode != 0:
            warnings.append(
                f"zramctl exited {zram_res.returncode}: {zram_res.stderr.strip()}"
            )
            return warnings

        mkswap_res = cmd.run(["mkswap", "/dev/zram0"])
        if mkswap_res.returncode != 0:
            warnings.append(
                f"mkswap exited {mkswap_res.returncode}: {mkswap_res.stderr.strip()}"
            )
            return warnings

        swapon_res = cmd.run(["swapon", "-p", "100", "/dev/zram0"])
        if swapon_res.returncode != 0:
            warnings.append(
                f"swapon exited {swapon_res.returncode}: {swapon_res.stderr.strip()}"
            )
    else:
        warnings.append("zramctl/mkswap/swapon not all available; skipped zram setup")

    return warnings
